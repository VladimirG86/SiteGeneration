CHIPS_RULES = """Ты помогаешь владельцу бизнеса заполнить анкету для создания сайта.
На основе описания бизнеса верни JSON с короткими подсказками, которые можно
добавить в поля анкеты одним кликом. Формулировки — как говорит владелец бизнеса,
конкретные, без воды. Верни ТОЛЬКО валидный JSON:
{"products": [...], "advantages": [...], "extras": [...]}
  products: 6-9 услуг/товаров, каждый 2-5 слов
  advantages: 6-8 преимуществ/фактов, каждый 2-6 слов (с цифрами, если уместно)
  extras: 4-6 «приятных мелочей»/условий работы (оплата, гарантия, логистика, бонусы)
"""


def build_site_messages(answers: dict, theme_mode: str, accent_name: str,
                        accent_hex: str):
    answers_text = "\n".join(f"- {k}: {v}" for k, v in answers.items() if v)
    user = SITE_RULES.format(
        theme_mode=theme_mode,
        accent_name=accent_name,
        accent_hex=accent_hex,
        answers=answers_text,
    ) + "\n\nСХЕМА JSON:\n" + SITE_SCHEMA
    return [
        {"role": "system", "content": SITE_RULES.split("СОСТАВ СТРАНИЦЫ")[0]},
        {"role": "user", "content": user},
    ]


def build_chips_messages(answers: dict):
    answers_text = "\n".join(f"- {k}: {v}" for k, v in answers.items() if v)
    return [
        {"role": "system", "content": CHIPS_RULES},
        {"role": "user",
         "content": "Описание бизнеса:\n" + answers_text},
    ]
