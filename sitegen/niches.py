def detect_niche(text: str) -> str:
    import re
    t = (text or "").lower()
    words = set(re.findall(r"[а-яёa-z0-9]+", t))
    best, score = "generic", 0
    for niche, kws in NICHE_KEYWORDS.items():
        s = 0
        for kw in kws:
            if kw in _WORD_ONLY:
                s += 1 if kw in words else 0
            elif kw in t:
                s += 1
        if s > score:
            best, score = niche, s
    return best


def chips_for(niche: str) -> dict:
    return CHIPS.get(niche, CHIPS["generic"])
